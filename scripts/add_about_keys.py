CATALOG_DIRS = [
    Path("frontend/src/localization/catalogs"),
    Path("src/translations")
]
LANGS = ["en", "hi", "te", "ta", "kn", "ml"]

def apply_keys():
    for base_dir in CATALOG_DIRS:
        if not base_dir.exists():
            continue
        for l in LANGS:
            fpath = base_dir / f"{l}.json"
            if not fpath.exists():
                continue
            with open(fpath, "r", encoding="utf-8") as f:
                data = json.load(f)

            added = 0
            for k, trans in NEW_KEYS.items():
                if k not in data or data[k] != trans[l]:
                    data[k] = trans[l]
                    added += 1

            with open(fpath, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
            print(f"Updated {fpath}: +{added} keys (Total: {len(data)})")

if __name__ == "__main__":
    apply_keys()
