def main():
    langs = ["en", "hi", "te", "ta", "kn", "ml"]
    for l in langs:
        frontend_path = CATALOGS_DIR / f"{l}.json"
        backend_path = SRC_TRANSLATIONS_DIR / f"{l}.json"

        with open(frontend_path, "r", encoding="utf-8") as f:
            cat = json.load(f)

        for k, translations in NEW_KEYS.items():
            cat[k] = translations[l]

        with open(frontend_path, "w", encoding="utf-8") as f:
            json.dump(cat, f, ensure_ascii=False, indent=2)

        if backend_path.exists():
            with open(backend_path, "r", encoding="utf-8") as f:
                bcat = json.load(f)
            for k, translations in NEW_KEYS.items():
                bcat[k] = translations[l]
            with open(backend_path, "w", encoding="utf-8") as f:
                json.dump(bcat, f, ensure_ascii=False, indent=2)

        print(f"Successfully updated {l}.json with {len(NEW_KEYS)} new keys.")

if __name__ == "__main__":
    main()
