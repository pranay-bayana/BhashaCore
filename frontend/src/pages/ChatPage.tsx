import React, { useState, useEffect, useRef, useCallback } from 'react';
import { useLanguage } from '@/localization/LanguageContext';
import { ChatMessage, ChatHistoryItem, Citation } from '@/types/api';
import { ChatSidebar } from '@/components/chat/ChatSidebar';
import { ChatWorkspace } from '@/components/chat/ChatWorkspace';
import { ChatComposer } from '@/components/chat/ChatComposer';
import {
  streamChat,
  stopChat,
  newChat,
  fetchHistory,
  renameConversation,
  deleteConversation,
  loadChat,
  fetchGuestStatus,
} from '@/services/api';

interface ChatPageProps {
  onNavigate: (route: string) => void;
  user?: { name: string; email: string } | null;
  onOpenAuthModal?: () => void;
}

export const ChatPage: React.FC<ChatPageProps> = ({ onNavigate, user, onOpenAuthModal }) => {
  const { t } = useLanguage();
  const [conversations, setConversations] = useState<ChatHistoryItem[]>([]);
  const [guestCount, setGuestCount] = useState<number>(0);
  const [guestQuotaReached, setGuestQuotaReached] = useState<boolean>(false);
  const [activeSessionId, setActiveSessionId] = useState<string>(() => {
    if (typeof window !== 'undefined') {
      const p = new URLSearchParams(window.location.search).get('id');
      if (p) return p;
    }
    return '';
  });

  const [title, setTitle] = useState<string>('New chat');
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [isStreaming, setIsStreaming] = useState<boolean>(false);
  const [canRetry, setCanRetry] = useState<boolean>(false);
  const [manualRetryUsed, setManualRetryUsed] = useState<boolean>(false);
  const [isCreatingNewChat, setIsCreatingNewChat] = useState<boolean>(false);
  const [sidebarCollapsed, setSidebarCollapsed] = useState<boolean>(false);
  const [isMobileSidebarOpen, setIsMobileSidebarOpen] = useState<boolean>(false);

  const abortControllerRef = useRef<AbortController | null>(null);
  const activeSessionIdRef = useRef<string>(activeSessionId);
  const loadedSessionIdRef = useRef<string>('');
  const justCreatedSidRef = useRef<string>('');

  useEffect(() => {
    activeSessionIdRef.current = activeSessionId;
  }, [activeSessionId]);

  // Sync guest trial status from server-side database session
  useEffect(() => {
    let cancelled = false;
    if (!user) {
      fetchGuestStatus().then((st) => {
        // Auth can resolve after this request starts.  Never let a stale
        // anonymous response re-lock an authenticated workspace.
        if (cancelled || st.authenticated) return;
        setGuestCount(st.guest_message_count);
        if (st.guest_quota_reached || st.guest_message_count >= 3) {
          setGuestQuotaReached(true);
        } else {
          setGuestQuotaReached(false);
        }
      });
    } else {
      setGuestCount(0);
      setGuestQuotaReached(false);
    }
    return () => { cancelled = true; };
  }, [user]);

  // Load conversation history from backend (supported for both guests and authenticated accounts)
  const loadHistoryList = useCallback(async () => {
    try {
      const list = await fetchHistory();
      setConversations(list || []);
    } catch (_) {
      setConversations([]);
    }
  }, []);

  useEffect(() => {
    loadHistoryList();
  }, [loadHistoryList, user]);

  // Load messages for the active session (works for both guests and authenticated users)
  useEffect(() => {
    if (!activeSessionId) {
      setMessages([]);
      setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');
      loadedSessionIdRef.current = '';
      return;
    }

    // If this session was just generated by handleNewChat, skip loading from server
    if (justCreatedSidRef.current === activeSessionId) {
      justCreatedSidRef.current = '';
      loadedSessionIdRef.current = activeSessionId;
      return;
    }

    // If we already have the messages loaded for this exact session, don't re-fetch/wipe
    if (loadedSessionIdRef.current === activeSessionId) {
      return;
    }

    let cancelled = false;
    const requestedSid = activeSessionId;

    // Load from backend session store
    loadChat(requestedSid).then((data) => {
      if (cancelled || activeSessionIdRef.current !== requestedSid) return;
      if (data && data.session && Array.isArray(data.session.messages) && data.session.messages.length > 0) {
        const msgs: ChatMessage[] = data.session.messages.map((m: any) => ({
          role: m.role === 'assistant' ? 'assistant' : 'user',
          content: m.content,
          status: m.status,
          citations: m.citations || [],
        }));
        setMessages(msgs);
        loadedSessionIdRef.current = requestedSid;
        const firstUser = msgs.find(m => m.role === 'user');
        if (firstUser) {
          setTitle(firstUser.content.slice(0, 45) + (firstUser.content.length > 45 ? '…' : ''));
        }
      } else {
        // Conversation has no messages on server or is not available
        // Clear stale ID from URL so it becomes clean /chat and show clean new-chat workspace
        if (typeof window !== 'undefined') {
          sessionStorage.removeItem('bhashacore_active_sid');
          const url = new URL(window.location.href);
          if (url.searchParams.has('id')) {
            url.searchParams.delete('id');
            window.history.replaceState({}, '', url.pathname + (url.search ? url.search : ''));
          }
        }
        setMessages([]);
        setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');
        setActiveSessionId('');
        activeSessionIdRef.current = '';
        loadedSessionIdRef.current = '';
      }
    }).catch(() => {
      // 404 or network error loading conversation: stale conversation no longer available
      // Clear stale ID from URL so it becomes clean /chat and show clean new-chat workspace
      if (typeof window !== 'undefined') {
        sessionStorage.removeItem('bhashacore_active_sid');
        const url = new URL(window.location.href);
        if (url.searchParams.has('id')) {
          url.searchParams.delete('id');
          window.history.replaceState({}, '', url.pathname + (url.search ? url.search : ''));
        }
      }
      setMessages([]);
      setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');
      setActiveSessionId('');
      activeSessionIdRef.current = '';
      loadedSessionIdRef.current = '';
    });

    return () => {
      cancelled = true;
    };
  }, [activeSessionId, t]);

  // Listen to browser Back / Forward navigation (popstate) to keep URL, state and sidebar in sync
  useEffect(() => {
    const handlePopState = () => {
      const p = new URLSearchParams(window.location.search).get('id');
      if (p) {
        if (p !== activeSessionIdRef.current) {
          if (abortControllerRef.current) {
            abortControllerRef.current.abort();
            setIsStreaming(false);
          }
          setActiveSessionId(p);
          activeSessionIdRef.current = p;
        }
      } else {
        // Navigated back to /chat without ?id (clean new chat)
        if (activeSessionIdRef.current) {
          if (abortControllerRef.current) {
            abortControllerRef.current.abort();
            setIsStreaming(false);
          }
          setActiveSessionId('');
          activeSessionIdRef.current = '';
          loadedSessionIdRef.current = '';
          setMessages([]);
          setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');
        }
      }
    };
    window.addEventListener('popstate', handlePopState);
    return () => window.removeEventListener('popstate', handlePopState);
  }, [t]);

  // Keyboard shortcut: Cmd+K / Ctrl+K for New Chat
  useEffect(() => {
    const handleKeyDown = (e: globalThis.KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
        e.preventDefault();
        handleNewChat();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, []);

  const handleSendMessage = async (
    question: string,
    options: { inputLang: string; inputStyle: string; answerLang: string | null; answerScript: string },
    isManualRetry = false,
  ) => {
    if (isStreaming) return;
    if (!isManualRetry) setManualRetryUsed(false);
    setCanRetry(false);

    let sid = activeSessionIdRef.current;
    if (!sid) {
      sid = typeof crypto !== 'undefined' && crypto.randomUUID
        ? crypto.randomUUID()
        : `sess-${Date.now()}-${Math.random().toString(36).substring(2, 9)}`;
      loadedSessionIdRef.current = sid;
      setActiveSessionId(sid);
      activeSessionIdRef.current = sid;
      if (typeof window !== 'undefined') {
        sessionStorage.setItem('bhashacore_active_sid', sid);
        const url = new URL(window.location.href);
        url.searchParams.set('id', sid);
        window.history.pushState({}, '', url.toString());
      }
    }

    const userMessage: ChatMessage = {
      role: 'user',
      content: question,
      created_at: new Date().toISOString(),
    };

    const newMessages = [...messages, userMessage];
    setMessages(newMessages);

    // Update conversation title optimistically
    if (messages.length === 0) {
      const displayTitle = question.slice(0, 40) + (question.length > 40 ? '…' : '');
      setTitle(displayTitle);
      setConversations(prev => [
        {
          id: sid,
          session_id: sid,
          title: displayTitle,
          created: Date.now() / 1000,
        },
        ...prev.filter(c => c.session_id !== sid)
      ]);
    }

    // Save to localStorage ONLY for authenticated users
    if (user) {
      try {
        localStorage.setItem(`bhashacore_chat_msgs_${sid}`, JSON.stringify(newMessages));
      } catch (_) {}
    }

    // Prepare assistant response
    const assistantIndex = newMessages.length;
    const initialAssistantMsg: ChatMessage = {
      role: 'assistant',
      content: '',
      status: t('status_searching') || 'Searching the corpus…',
      citations: [],
    };

    setMessages([...newMessages, initialAssistantMsg]);
    setIsStreaming(true);

    const controller = new AbortController();
    abortControllerRef.current = controller;

    let accumulatedContent = '';
    let finalCitations: Citation[] = [];
    let finalStatus = 'Answered';

    try {
      await streamChat(
        {
          question,
          session_id: sid,
          input_lang: options.inputLang,
          input_style: options.inputStyle,
          answer_lang: options.answerLang || undefined,
          answer_script: options.answerScript,
        },
        (event) => {
          if (event.type === 'meta') {
            if (typeof (event as any).guest_message_count === 'number') {
              setGuestCount((event as any).guest_message_count);
            }
            setMessages(prev => {
              if (prev.length === 0) return prev;
              const updated = [...prev];
              const idx = updated.length > assistantIndex ? assistantIndex : updated.length - 1;
              if (updated[idx]) {
                updated[idx].status = `${t('status_searching') || 'Searching'} (${(event.lang || '').toUpperCase()})`;
              }
              return updated;
            });
          } else if (event.type === 'delta') {
            accumulatedContent += event.text;
            setMessages(prev => {
              if (prev.length === 0) return prev;
              const updated = [...prev];
              const idx = updated.length > assistantIndex ? assistantIndex : updated.length - 1;
              if (updated[idx]) {
                updated[idx].content = accumulatedContent;
              }
              return updated;
            });
          } else if (event.type === 'done') {
            finalCitations = event.citations || [];
            const citeCount = finalCitations.length;

            if (typeof (event as any).guest_message_count === 'number') {
              setGuestCount((event as any).guest_message_count);
            }
            if ((event as any).guest_quota_reached || (!user && (event as any).guest_message_count >= 3)) {
              setGuestQuotaReached(true);
            }

            if (event.status === 'answered') {
              const template = t('status_answered') || 'Answered — grounded in {count} retrieved passage{plural}';
              finalStatus = template
                .replace('{count}', String(citeCount))
                .replace('{plural}', citeCount === 1 ? '' : 's');
            } else if (event.status === 'insufficient_evidence') {
              finalStatus = t('status_insufficient') || 'Insufficient evidence — not answered';
            } else if (event.status === 'stopped') {
              finalStatus = t('status_stopped') || 'Stopped by user.';
            }

            setMessages(prev => {
              if (prev.length === 0) return prev;
              const updated = [...prev];
              const idx = updated.length > assistantIndex ? assistantIndex : updated.length - 1;
              if (updated[idx]) {
                updated[idx].content = accumulatedContent || event.answer;
                updated[idx].status = finalStatus;
                updated[idx].citations = finalCitations;
              }
              // Save complete conversation to local cache ONLY for authenticated users
              if (user) {
                try {
                  localStorage.setItem(`bhashacore_chat_msgs_${sid}`, JSON.stringify(updated));
                } catch (_) {}
              }
              return updated;
            });

            // Reload history to ensure titles and counters are synced for everyone
            loadHistoryList();
            fetchGuestStatus().then(st => {
              setGuestCount(st.guest_message_count);
              if (st.guest_quota_reached || st.guest_message_count >= 3) {
                setGuestQuotaReached(true);
              }
            });
          } else if (event.type === 'error') {
            if (event.error?.includes('guest_quota') || event.error?.toLowerCase().includes('trial limit')) {
              setGuestQuotaReached(true);
            }
            setCanRetry(Boolean(event.retryable) && !isManualRetry);
            setMessages(prev => {
              const updated = [...prev];
              if (updated[assistantIndex]) {
                // The API supplies only a safe public message.  Do not show a
                // raw provider status/body, and do not leave a blank loading
                // bubble when a stream ends without a completion marker.
                updated[assistantIndex].content = event.message || event.error;
                updated[assistantIndex].status = event.retryable ? 'Retry available' : 'Error';
              }
              return updated;
            });
          }
        },
        controller.signal
      );
    } catch (err: any) {
      if (err.name !== 'AbortError') {
        console.error('Stream error:', err);
      }
    } finally {
      setIsStreaming(false);
      abortControllerRef.current = null;
    }
  };

  const handleStop = async () => {
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
    }
    await stopChat(activeSessionId);
    setIsStreaming(false);
  };

  const handleNewChat = async () => {
    if (isCreatingNewChat) return;
    setIsCreatingNewChat(true);

    if (isStreaming) handleStop();

    // 1. Immediately reset messages and title so welcome screen appears without lag
    setMessages([]);
    setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');

    // 2. Synchronously generate new session ID and activate it immediately to eliminate race conditions
    const newSid = typeof crypto !== 'undefined' && crypto.randomUUID
      ? crypto.randomUUID()
      : `sess-${Date.now()}-${Math.random().toString(36).substring(2, 9)}`;
    setActiveSessionId(newSid);
    activeSessionIdRef.current = newSid;
    justCreatedSidRef.current = newSid;
    loadedSessionIdRef.current = newSid;

    if (typeof window !== 'undefined') {
      sessionStorage.setItem('bhashacore_active_sid', newSid);
      const url = new URL(window.location.href);
      url.searchParams.set('id', newSid);
      window.history.pushState({}, '', url.toString());
    }

    // 3. Immediately clear and focus composer textarea
    const inputEl = document.getElementById('questionInput') as HTMLTextAreaElement | null;
    if (inputEl) {
      inputEl.value = '';
      inputEl.focus();
    }

    try {
      // 4. Register or allocate new session from backend with the exact new ID
      await newChat(newSid);
      await loadHistoryList();
    } catch (err) {
      console.warn('handleNewChat error:', err);
    } finally {
      setIsCreatingNewChat(false);
      setTimeout(() => {
        const inputEl = document.getElementById('questionInput') as HTMLTextAreaElement | null;
        if (inputEl) inputEl.focus();
      }, 50);
    }
  };

  const handleSelectConversation = (sessionId: string) => {
    if (isStreaming) handleStop();
    setMessages([]);
    setTitle(t('chat_new_conversation') || t('nav_new_chat') || 'New chat');
    setActiveSessionId(sessionId);
    activeSessionIdRef.current = sessionId;
    if (typeof window !== 'undefined') {
      sessionStorage.setItem('bhashacore_active_sid', sessionId);
      const url = new URL(window.location.href);
      url.searchParams.set('id', sessionId);
      window.history.pushState({}, '', url.toString());
    }
  };

  const handleRename = async (id: string, newTitle: string) => {
    const success = await renameConversation(id, newTitle);
    if (success) {
      setConversations(prev =>
        prev.map(c => c.id === id ? { ...c, title: newTitle } : c)
      );
      if (activeSessionId === id) {
        setTitle(newTitle);
      }
    }
  };

  const handleDelete = async (id: string) => {
    const success = await deleteConversation(id);
    if (success) {
      setConversations(prev => prev.filter(c => c.id !== id));
      localStorage.removeItem(`bhashacore_chat_msgs_${id}`);
      if (activeSessionId === id) {
        handleNewChat();
      }
    }
  };

  const handleRetry = () => {
    if (manualRetryUsed || isStreaming || !canRetry) return;
    setManualRetryUsed(true);
    setCanRetry(false);
    const lastUserMsg = [...messages].reverse().find(m => m.role === 'user');
    if (lastUserMsg) {
      handleSendMessage(lastUserMsg.content, {
        inputLang: 'auto',
        inputStyle: 'auto',
        answerLang: null,
        answerScript: 'native',
      }, true);
    }
  };

  return (
    <div className="flex h-[calc(100vh-4rem)] overflow-hidden relative">
      {/* 1. Left Conversation Sidebar */}
      <ChatSidebar
        conversations={conversations}
        activeSessionId={activeSessionId}
        onSelectConversation={handleSelectConversation}
        onNewChat={handleNewChat}
        onRenameConversation={handleRename}
        onDeleteConversation={handleDelete}
        collapsed={sidebarCollapsed}
        onToggleCollapse={() => setSidebarCollapsed(!sidebarCollapsed)}
        isMobileOpen={isMobileSidebarOpen}
        onCloseMobile={() => setIsMobileSidebarOpen(false)}
        user={user}
        onOpenResearch={() => onNavigate('dashboard')}
        onOpenSettings={() => onNavigate('settings')}
        onOpenAuthModal={onOpenAuthModal}
        guestCount={guestCount}
      />

      {/* 2. Main Workspace & Composer Column */}
      <main className="flex-1 flex flex-col h-full overflow-hidden bg-transparent relative">
        <ChatWorkspace
          messages={messages}
          title={title}
          isStreaming={isStreaming}
          onSelectPromptStarter={(question) => {
            handleSendMessage(question, {
              inputLang: 'auto',
              inputStyle: 'auto',
              answerLang: null,
              answerScript: 'native',
            });
          }}
          onNewChat={handleNewChat}
          onToggleSidebar={() => {
            if (window.innerWidth < 768) {
              setIsMobileSidebarOpen(true);
            } else {
              setSidebarCollapsed(false);
            }
          }}
          sidebarCollapsed={sidebarCollapsed}
          isGuestQuotaReached={guestQuotaReached}
          onOpenAuthModal={onOpenAuthModal}
          user={user}
        />

        {/* Floating Bottom Composer */}
        <ChatComposer
          onSendMessage={handleSendMessage}
          onStop={handleStop}
          onRetry={canRetry && !manualRetryUsed && !isStreaming ? handleRetry : undefined}
          isStreaming={isStreaming}
          disabled={guestQuotaReached}
          isGuestQuotaReached={guestQuotaReached}
          onOpenAuthModal={onOpenAuthModal}
          activeSessionId={activeSessionId}
        />
      </main>
    </div>
  );
};
